PRICE_COLUMNS = ["date", "close", "adj_close", "dividend", "split_factor"]


def standardize_prices(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
    d = pd.to_datetime(df["date"])
    if getattr(d.dt, "tz", None) is not None:
        d = d.dt.tz_localize(None)
    df["date"] = d.dt.normalize().astype("datetime64[ns]")
    for c in ["close", "adj_close", "dividend", "split_factor"]:
        if c not in df.columns:
            df[c] = np.nan if c in ("close", "adj_close") else (0.0 if c == "dividend" else 1.0)
        df[c] = pd.to_numeric(df[c], errors="coerce")
    df["dividend"] = df["dividend"].fillna(0.0)
    df["split_factor"] = df["split_factor"].replace(0, 1.0).fillna(1.0)
    df = df[PRICE_COLUMNS].dropna(subset=["close"])
    df = df[df["close"] > 0]
    return df.sort_values("date").reset_index(drop=True)


def parse_yfinance_csv(content: bytes) -> pd.DataFrame:
    df = pd.read_csv(io.BytesIO(content))
    ren = {"Date": "date", "Close": "close", "Adj Close": "adj_close", "Dividends": "dividend",
           "Stock Splits": "split_factor"}
    df = df.rename(columns=ren)
    df["date"] = pd.to_datetime(df["date"].astype(str).str[:10])
    # Mutual funds can pay capital-gain distributions, which yfinance reports in a separate
    # column. They lower the NAV like any other distribution, so they count as distributions.
    if "Capital Gains" in df.columns:
        base = pd.to_numeric(df["dividend"], errors="coerce").fillna(0.0) if "dividend" in df.columns else 0.0
        df["dividend"] = base + pd.to_numeric(df["Capital Gains"], errors="coerce").fillna(0.0)
    # yfinance reports 0 on non-split days. Yahoo closes are already split-adjusted, so the
    # split column is informational only.
    df["split_factor"] = 1.0
    return standardize_prices(df)


def parse_yahoo_chart_json(content: bytes) -> pd.DataFrame:
    """Parse the Yahoo v8 chart API (verified structure 2026-11-02): result[0].timestamp,
    indicators.quote[0].close (split-adjusted), indicators.adjclose[0].adjclose,
    events.dividends and events.capitalGains {ts: {amount, date}}. Timestamps are market-open
    times in UTC. For a mutual fund the close is the daily NAV."""
    obj = json.loads(content)
    chart = obj.get("chart", {})
    if chart.get("error"):
        raise SourceError(f"Yahoo chart error: {chart['error']}")
    res = chart["result"][0]
    ts = res.get("timestamp") or []
    if not ts:
        raise SourceError("Yahoo chart returned no observations (the symbol may have no history)")
    tzname = res.get("meta", {}).get("exchangeTimezoneName", "America/New_York")
    dates = pd.to_datetime(ts, unit="s", utc=True).tz_convert(tzname).tz_localize(None).normalize()
    quote = res["indicators"]["quote"][0]
    adj = res["indicators"].get("adjclose", [{}])[0].get("adjclose", [np.nan] * len(ts))
    df = pd.DataFrame({"date": dates, "close": quote["close"], "adj_close": adj})
    events = res.get("events", {}) or {}
    # Dividends and, for mutual funds, capital-gain distributions both lower the NAV on the
    # ex-date, so both count as distributions.
    dist = list((events.get("dividends") or {}).values()) + list((events.get("capitalGains") or {}).values())
    if dist:
        dd = pd.DataFrame(dist)
        dd["date"] = pd.to_datetime(dd["date"], unit="s", utc=True).dt.tz_convert(tzname).dt.tz_localize(None).dt.normalize()
        dd = dd.groupby("date")["amount"].sum()
        df["dividend"] = df["date"].map(dd).fillna(0.0)
    else:
        df["dividend"] = 0.0
    df["split_factor"] = 1.0
    return standardize_prices(df)


def parse_tiingo_json(content: bytes) -> pd.DataFrame:
    """Tiingo daily prices (documented, untested here): close is unadjusted, divCash is the
    cash distribution on the ex-date, splitFactor marks splits. We convert to split-adjusted closes."""
    df = pd.DataFrame(json.loads(content))
    df = df.rename(columns={"adjClose": "adj_close", "divCash": "dividend", "splitFactor": "split_factor"})
    df["date"] = pd.to_datetime(df["date"].astype(str).str[:10])
    df = df.sort_values("date")
    later_splits = df["split_factor"].fillna(1.0)[::-1].cumprod()[::-1].shift(-1).fillna(1.0)
    df["close"] = df["close"] / later_splits
    df["dividend"] = df["dividend"].fillna(0.0) / later_splits
    df["split_factor"] = 1.0
    return standardize_prices(df)


def parse_local_prices(content: bytes) -> pd.DataFrame:
    """User-provided prices: columns date, close (split-adjusted, NOT distribution-adjusted),
    dividend (cash amount on the ex-date, 0 otherwise), optional adj_close."""
    df = pd.read_csv(io.BytesIO(content))
    df.columns = [c.strip().lower() for c in df.columns]
    if "close" not in df.columns or "date" not in df.columns:
        raise SourceError("Local price file needs at least columns: date, close, dividend")
    if "dividend" not in df.columns:
        raise SourceError("Local price file needs a dividend column (use 0 when none). An adjusted "
                          "price alone is not a substitute, because the project rebuilds total returns.")
    return standardize_prices(df)


def _to_epoch(date_str: str) -> int:
    return int(pd.Timestamp(date_str, tz="UTC").timestamp())


def fetch_prices(ticker: str, store: RawStore, cfg: dict, local_dir: Path, start: str, end: str | None,
                 refresh: bool, role: str = "") -> pd.DataFrame:
    dataset = f"prices_{ticker}"
    units = "USD per share; dividend = cash per share on the ex-date"
    rule = "known at that day's 4 pm ET close"
    cached = None if refresh else store.latest(dataset)
    if cached is not None:
        df = parse_price_file(store.file_path(cached), cached["provider"])
        store.add_status(dataset, "cached", cached["provider"], f"reused {cached['file']}", role)
        return df
    end = end or (pd.Timestamp.today() + pd.Timedelta(days=1)).strftime("%Y-%m-%d")
    errors = []
    for provider in cfg["data"]["price_providers"]:
        try:
            if provider == "yfinance":
                import yfinance as yf  # optional dependency
                hist = yf.Ticker(ticker).history(start=start, end=end, interval="1d", auto_adjust=False,
                                                 actions=True)
                if hist is None or hist.empty:
                    raise SourceError("yfinance returned no rows")
                hist = hist.reset_index()
                hist["Date"] = pd.to_datetime(hist["Date"]).dt.strftime("%Y-%m-%d")
                content = hist.to_csv(index=False).encode()
                df = parse_yfinance_csv(content)
                notes = "yfinance Ticker.history(auto_adjust=False, actions=True): Close split-adjusted, Dividends on ex-date"
                ext = "csv"
                url = f"yfinance:{ticker}"
            elif provider == "yahoo_chart":
                url = f"https://query1.finance.yahoo.com/v8/finance/chart/{ticker}"
                params = {"period1": _to_epoch(start), "period2": _to_epoch(end), "interval": "1d",
                          "events": "div,split,capitalGain", "includeAdjustedClose": "true"}
                content = http_get(url, cfg, params=params)
                df = parse_yahoo_chart_json(content)
                notes = "Yahoo v8 chart JSON: quote.close split-adjusted, events.dividends on ex-date"
                ext = "json"
            elif provider == "tiingo":
                key = os.environ.get("TIINGO_API_KEY")
                if not key:
                    raise SourceError("TIINGO_API_KEY not set")
                url = f"https://api.tiingo.com/tiingo/daily/{ticker}/prices"
                content = http_get(url, cfg, params={"startDate": start, "endDate": end, "token": key})
                df = parse_tiingo_json(content)
                notes = "Tiingo daily: close unadjusted (converted), divCash on ex-date"
                ext = "json"
            elif provider == "local":
                local = Path(local_dir) / f"{ticker}_prices.csv"
                if not local.exists():
                    raise SourceError(f"no local file {local}")
                content = local.read_bytes()
                df = parse_local_prices(content)
                notes = "user-provided: date, close, dividend"
                ext = "csv"
                url = str(local)
            else:
                raise SourceError(f"unknown provider {provider}")
            if len(df) < 20:
                raise SourceError(f"only {len(df)} rows")
            store.save(dataset, provider, url, content, ext, len(df), df["date"].min().date(),
                       df["date"].max().date(), units, notes, rule)
            status = "user_provided" if provider == "local" else "verified_access"
            store.add_status(dataset, status, provider, f"{len(df)} rows {df['date'].min().date()} to {df['date'].max().date()}", role)
            return df
        except Exception as exc:
            errors.append(f"{provider}: {type(exc).__name__}: {exc}")
    store.add_status(dataset, "unavailable", "", " | ".join(errors), role)
    raise SourceError(f"{ticker} prices unavailable. Tried: {' | '.join(errors)}. Fallback: save "
                      f"{Path(local_dir) / (ticker + '_prices.csv')} with columns date, close, dividend.")


def parse_price_file(path: Path, provider: str) -> pd.DataFrame:
    content = Path(path).read_bytes()
    if provider == "yfinance" or provider == "synthetic":
        return parse_yfinance_csv(content)
    if provider == "yahoo_chart":
        return parse_yahoo_chart_json(content)
    if provider == "tiingo":
        return parse_tiingo_json(content)
    return parse_local_prices(content)


