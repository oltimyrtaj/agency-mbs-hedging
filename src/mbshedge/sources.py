# FHFA National Mortgage Database (NMDB) outstanding-mortgage statistics
# ----------------------------------------------------------------------------
def parse_nmdb(content: bytes, national_only: bool = True) -> pd.DataFrame:
    """Parse the NMDB outstanding-statistics zip (or its CSV).

    Verified layout (2026-11-02): one CSV with columns SOURCE, FREQUENCY, GEOLEVEL, GEOID,
    GEONAME, MARKET, PERIOD (e.g. 2013Q1), YEAR, QUARTER, MONTH, SUPPRESSED, SERIESID,
    VALUE1 (weighted by loan count), VALUE2 (weighted by unpaid balance). National rows
    have GEOLEVEL == 'National'. Markets: All Mortgages, Enterprise Acquisitions,
    Government / Non-Conventional, Other Conventional Market.
    """
    if content[:2] == b"PK":
        with zipfile.ZipFile(io.BytesIO(content)) as zf:
            names = [n for n in zf.namelist() if n.lower().endswith(".csv")]
            if not names:
                raise SourceError("NMDB zip contains no CSV file")
            raw = zf.read(names[0])
    else:
        raw = content
    df = pd.read_csv(io.BytesIO(raw), dtype=str, keep_default_na=False)
    df.columns = [c.strip().upper() for c in df.columns]
    missing = [c for c in ["GEOLEVEL", "MARKET", "PERIOD", "SERIESID", "VALUE1", "VALUE2"] if c not in df.columns]
    if missing:
        raise SourceError(f"NMDB file is missing columns {missing}. Columns found: {list(df.columns)}. "
                          "Compare with the data dictionary and update parse_nmdb.")
    if national_only:
        df = df[df["GEOLEVEL"].str.strip() == "National"]
        if df.empty:
            raise SourceError("NMDB file has no rows with GEOLEVEL == 'National'")
    out = pd.DataFrame({
        "period": df["PERIOD"].str.strip(),
        "market": df["MARKET"].str.strip(),
        "series": df["SERIESID"].str.strip(),
        "value1": pd.to_numeric(df["VALUE1"], errors="coerce"),
        "value2": pd.to_numeric(df["VALUE2"], errors="coerce"),
        "suppressed": pd.to_numeric(df.get("SUPPRESSED", "0"), errors="coerce").fillna(0).astype(int),
    })
    qq = out["period"].str.extract(r"^(\d{4})Q([1-4])$")
    if qq.isna().any().any():
        raise SourceError("NMDB PERIOD values are not all of the form YYYYQn")
    out["quarter_end"] = pd.PeriodIndex.from_fields(year=qq[0].astype(int).to_numpy(), quarter=qq[1].astype(int).to_numpy(),
                                                    freq="Q").to_timestamp(how="end").normalize().astype("datetime64[ns]")
    return out.sort_values(["series", "market", "quarter_end"]).reset_index(drop=True)


def fetch_nmdb(store: RawStore, cfg: dict, local_dir: Path, refresh: bool) -> pd.DataFrame:
    dataset = "fhfa_nmdb_outstanding_national_census"
    ncfg = cfg["data"]["nmdb"]
    lag = cfg["timing"]["nmdb_lag_quarters"]
    rule = f"quarter q usable at the end of quarter q+{lag} (approximation: series published years later)"
    notes = "long format; VALUE1 count-weighted, VALUE2 UPB-weighted; rates in percent; TOT_UPB in $ billions"
    cached = None if refresh else store.latest(dataset)
    if cached is not None:
        df = parse_nmdb(store.file_path(cached).read_bytes())
        store.add_status(dataset, "cached", cached["provider"], f"reused {cached['file']}", "core")
        return df
    errors = []
    try:
        content = http_get(ncfg["zip_url"], cfg)
        df = parse_nmdb(content)
        store.save(dataset, "fhfa_zip", ncfg["zip_url"], content, "zip", len(df),
                   df["period"].min(), df["period"].max(), "see field notes", notes, rule)
        store.add_status(dataset, "verified_access", "fhfa_zip", f"{len(df)} national rows, {df['period'].min()} to {df['period'].max()}", "core")
        return df
    except Exception as exc:
        errors.append(f"fhfa_zip: {exc}")
    for local in sorted(Path(local_dir).glob("*nmdb*")):
        if local.suffix.lower() in (".zip", ".csv"):
            content = local.read_bytes()
            df = parse_nmdb(content)
            store.save(dataset, "local_file", str(local), content, local.suffix.lstrip("."), len(df),
                       df["period"].min(), df["period"].max(), "see field notes", notes, rule)
            store.add_status(dataset, "user_provided", "local_file", str(local), "core")
            return df
    store.add_status(dataset, "unavailable", "", " | ".join(errors), "core")
    raise SourceError("NMDB unavailable (" + " | ".join(errors) + "). Download the 'National, Census Regions, and "
                      f"Census Divisions [CSV]' zip from {ncfg['page_url']} and save it in {local_dir}.")


def fetch_document(name: str, url: str, store: RawStore, cfg: dict, refresh: bool, ext: str = "pdf") -> str:
    """Fetch a documentation file (for the record). Never blocks the pipeline."""
    dataset = f"doc_{name}"
    if not refresh and store.latest(dataset) is not None:
        store.add_status(dataset, "cached", "", "documentation already saved", "documentation")
        return "cached"
    try:
        content = http_get(url, cfg)
        store.save(dataset, "http", url, content, ext, 0, "", "", "", "documentation", "n/a")
        store.add_status(dataset, "verified_access", "http", url, "documentation")
        return "verified_access"
    except Exception as exc:
        store.add_status(dataset, "unavailable", "", str(exc), "documentation")
        return "unavailable"


