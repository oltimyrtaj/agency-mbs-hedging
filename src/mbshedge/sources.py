"""Data adapters with caching, bounded retries, immutable raw files, and a manifest.

Raw files are never overwritten. Each download is saved under data/raw/<dataset>/ with a
UTC timestamp in its name, and data/raw/manifest.csv records its source URL, provider,
retrieval time, SHA-256 hash, size, row count, date span, units, field notes, and the
availability rule used later in the pipeline. With `refresh: false` a re-run reuses the
latest cached file for each dataset.

Access status vocabulary (written to results/data_status/access_status.csv)
---------------------------------------------------------------------------
verified_access  downloaded and parsed successfully in this run
cached           an earlier verified download was reused
user_provided    loaded from data/local_inputs/ (schema in docs/data_sources.md)
synthetic        generated by mbshedge.synthetic (smoke run only)
unavailable      every route failed (messages explain why)

Optional credentials come only from environment variables: FRED_API_KEY, TIINGO_API_KEY.
"""
from __future__ import annotations

import hashlib
import io
import json
import os
import time
import zipfile
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

MANIFEST_COLUMNS = [
    "dataset", "provider", "source_url", "retrieved_at_utc", "file", "sha256", "bytes", "rows",
    "first_date", "last_date", "units", "field_notes", "availability_rule", "synthetic",
]

NMDB_COLUMNS = ["SOURCE", "FREQUENCY", "GEOLEVEL", "GEOID", "GEONAME", "MARKET", "PERIOD", "YEAR",
                "QUARTER", "MONTH", "SUPPRESSED", "SERIESID", "VALUE1", "VALUE2"]


class SourceError(RuntimeError):
    """Raised when a data source cannot be reached or parsed."""


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def sha256_bytes(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# ----------------------------------------------------------------------------
# HTTP with bounded retries
# ----------------------------------------------------------------------------
# Hosts that did not answer in time earlier in this run. Later requests to them fail at once,
# so one unresponsive server costs seconds instead of minutes.
_STALLED_HOSTS: set[str] = set()
_STALLED_CURL_HOSTS: set[str] = set()


def _host(url: str) -> str:
    from urllib.parse import urlparse
    return urlparse(url).netloc


def http_get(url: str, cfg: dict, params: dict | None = None, headers: dict | None = None) -> bytes:
    import requests  # imported lazily so the smoke run never needs network code

    host = _host(url)
    if host in _STALLED_HOSTS:
        raise SourceError(f"GET {url} skipped: {host} did not answer earlier in this run")
    net = cfg["network"]
    hdrs = {"User-Agent": net["user_agent"]}
    hdrs.update(headers or {})
    timeout = (float(net.get("connect_timeout_seconds", 10)), float(net["timeout_seconds"]))
    last_err, timeouts = None, 0
    for attempt in range(int(net["max_retries"])):
        try:
            resp = requests.get(url, params=params, headers=hdrs, timeout=timeout)
            if resp.status_code == 200 and resp.content:
                return resp.content
            last_err = f"HTTP {resp.status_code}"
            if resp.status_code in (401, 403, 404):
                break  # retrying will not help
        except requests.exceptions.Timeout as exc:
            timeouts += 1
            last_err = f"{type(exc).__name__}: {exc}"
        except Exception as exc:  # other network errors, proxy refusals
            last_err = f"{type(exc).__name__}: {exc}"
        time.sleep(float(net["backoff_seconds"]) * (2 ** attempt))
    if timeouts == int(net["max_retries"]):
        _STALLED_HOSTS.add(host)
    raise SourceError(f"GET {url} failed after retries ({last_err})")


def curl_get(url: str, cfg: dict, params: dict | None = None) -> bytes:
    """The same request through the system's curl program, a different HTTP client from
    Python's. Some servers answer one and stall the other."""
    import shutil
    import subprocess
    from urllib.parse import urlencode

    host = _host(url)
    curl = shutil.which("curl")
    if curl is None:
        raise SourceError("curl is not installed")
    if host in _STALLED_CURL_HOSTS:
        raise SourceError(f"curl {url} skipped: {host} did not answer curl earlier in this run")
    net = cfg["network"]
    full = url + ("?" + urlencode(params) if params else "")
    limit = float(net.get("curl_max_seconds", 45))
    try:
        res = subprocess.run([curl, "-sS", "-f", "-L", "--connect-timeout", str(net.get("connect_timeout_seconds", 10)),
                              "-m", str(limit), "-A", net["user_agent"], full],
                             capture_output=True, timeout=limit + 10)
    except subprocess.TimeoutExpired:
        _STALLED_CURL_HOSTS.add(host)
        raise SourceError(f"curl {url} did not finish in {limit:.0f} s")
    if res.returncode != 0 or not res.stdout:
        if res.returncode == 28:  # curl's own timeout
            _STALLED_CURL_HOSTS.add(host)
        raise SourceError(f"curl {url} failed (exit {res.returncode}): {res.stderr.decode(errors='replace').strip()[:200]}")
    return res.stdout


# ----------------------------------------------------------------------------
# Raw store and manifest
# ----------------------------------------------------------------------------
@dataclass
class RawStore:
    raw_dir: Path
    status_rows: list = field(default_factory=list)

    def __post_init__(self):
        self.raw_dir = Path(self.raw_dir)
        self.raw_dir.mkdir(parents=True, exist_ok=True)

    @property
    def manifest_path(self) -> Path:
        return self.raw_dir / "manifest.csv"

    def manifest(self) -> pd.DataFrame:
        if self.manifest_path.exists():
            return pd.read_csv(self.manifest_path, dtype=str, keep_default_na=False)
        return pd.DataFrame(columns=MANIFEST_COLUMNS)

    def latest(self, dataset: str) -> dict | None:
        m = self.manifest()
        m = m[m["dataset"] == dataset]
        if m.empty:
            return None
        row = m.iloc[-1].to_dict()
        return row if self.file_path(row).exists() else None

    def file_path(self, row: dict) -> Path:
        p = Path(row["file"])
        if p.is_absolute():
            return p
        # manifest stores paths relative to the raw directory
        return self.raw_dir / p

    def save(self, dataset: str, provider: str, source_url: str, content: bytes, ext: str,
             rows: int, first_date: str, last_date: str, units: str, field_notes: str,
             availability_rule: str, synthetic: bool = False) -> dict:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
        folder = self.raw_dir / dataset
        folder.mkdir(parents=True, exist_ok=True)
        path = folder / f"{dataset}__{provider}__{stamp}.{ext}"
        with open(path, "xb") as fh:  # "x": never overwrite an existing raw file
            fh.write(content)
        try:
            path.chmod(0o444)  # read-only, so raw files stay immutable
        except OSError:
            pass
        row = {
            "dataset": dataset, "provider": provider, "source_url": source_url,
            "retrieved_at_utc": utc_now(), "file": str(path.relative_to(self.raw_dir)).replace(os.sep, "/"),
            "sha256": sha256_bytes(content), "bytes": str(len(content)), "rows": str(rows),
            "first_date": str(first_date), "last_date": str(last_date), "units": units,
            "field_notes": field_notes, "availability_rule": availability_rule,
            "synthetic": str(bool(synthetic)),
        }
        m = self.manifest()
        m = pd.concat([m, pd.DataFrame([row])], ignore_index=True)
        m.to_csv(self.manifest_path, index=False)
        return row

    def add_status(self, dataset: str, status: str, provider: str, message: str, role: str = "") -> None:
        self.status_rows.append({"dataset": dataset, "role": role, "status": status,
                                 "provider": provider, "message": message, "checked_at_utc": utc_now()})

    def status_table(self) -> pd.DataFrame:
        return pd.DataFrame(self.status_rows, columns=["dataset", "role", "status", "provider", "message",
                                                       "checked_at_utc"])

    def verify_hashes(self) -> pd.DataFrame:
        """Recompute every manifest hash. A mismatch means a raw file was altered."""
        m = self.manifest()
        out = []
        for _, row in m.iterrows():
            p = self.file_path(row.to_dict())
            ok = p.exists() and sha256_file(p) == row["sha256"]
            out.append({"file": row["file"], "exists": p.exists(), "hash_ok": ok})
        return pd.DataFrame(out)


