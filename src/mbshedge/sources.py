# FRED
# ----------------------------------------------------------------------------
FRED_GRAPH_URL = "https://fred.stlouisfed.org/graph/fredgraph.csv"
FRED_API_URL = "https://api.stlouisfed.org/fred/series/observations"


def parse_fred_csv(content: bytes | str | Path, series_id: str) -> pd.DataFrame:
    """Parse a FRED graph CSV. Verified layout (2026-11-02): header `observation_date,<ID>`,
    non-trading days present with an empty value. Older files used `DATE` and `.`."""
    if isinstance(content, (str, Path)) and Path(content).exists():
        content = Path(content).read_bytes()
    if isinstance(content, str):
        content = content.encode()
    df = pd.read_csv(io.BytesIO(content), dtype=str, keep_default_na=False)
    date_col = next((c for c in df.columns if c.strip().lower() in ("observation_date", "date")), None)
    if date_col is None:
        raise SourceError(f"FRED CSV for {series_id} has no date column: {list(df.columns)}")
    val_col = series_id if series_id in df.columns else [c for c in df.columns if c != date_col][0]
    out = pd.DataFrame({
        "date": pd.to_datetime(df[date_col]).astype("datetime64[ns]"),
        "value": pd.to_numeric(df[val_col].replace({".": "", "": np.nan}), errors="coerce"),
    })
    if out["date"].duplicated().any():
        raise SourceError(f"FRED {series_id}: duplicate dates in the download")
    return out.sort_values("date").reset_index(drop=True)


def parse_fred_api_json(content: bytes) -> pd.DataFrame:
    obs = json.loads(content)["observations"]
    df = pd.DataFrame(obs)
    return pd.DataFrame({
        "date": pd.to_datetime(df["date"]).astype("datetime64[ns]"),
        "value": pd.to_numeric(df["value"].replace(".", np.nan), errors="coerce"),
    }).sort_values("date").reset_index(drop=True)


def fetch_fred(series_id: str, store: RawStore, cfg: dict, local_dir: Path, start: str, end: str | None,
               refresh: bool, role: str = "") -> pd.DataFrame:
    dataset = f"fred_{series_id}"
    units = "percent" + (" (weekly, dated by Thursday release)" if series_id == "MORTGAGE30US" else " (daily)")
    rule = ("usable at the close of the Thursday release date (12:00 ET)" if series_id == "MORTGAGE30US"
            else "market-observable, treated as known at that day's close")
    cached = None if refresh else store.latest(dataset)
    if cached is not None:
        df = _parse_cached_fred(store, cached, series_id)
        store.add_status(dataset, "cached", cached["provider"], f"reused {cached['file']} ({cached['retrieved_at_utc']})", role)
        return df
    errors = []
    end = end or datetime.now(timezone.utc).strftime("%Y-%m-%d")
    # Routes 1 and 2: FRED graph CSV (no key), through Python, then through the system's curl
    url = FRED_GRAPH_URL
    params = {"id": series_id, "cosd": start, "coed": end}
    for provider, getter in (("fred_graph_csv", http_get), ("fred_graph_csv_curl", curl_get)):
        try:
            content = getter(url, cfg, params=params)
            df = parse_fred_csv(content, series_id)
            _check_nonempty(df, series_id)
            store.save(dataset, provider, f"{url}?id={series_id}&cosd={start}&coed={end}", content, "csv",
                       len(df), df["date"].min().date(), df["date"].max().date(), units,
                       "observation_date,<ID>; blank = no observation", rule)
            store.add_status(dataset, "verified_access", provider, f"{len(df)} rows", role)
            return df
        except Exception as exc:
            errors.append(f"{provider}: {exc}")
    # Route 3: FRED API (needs FRED_API_KEY)
    key = os.environ.get("FRED_API_KEY")
    if key:
        try:
            content = http_get(FRED_API_URL, cfg, params={"series_id": series_id, "api_key": key, "file_type": "json",
                                                           "observation_start": start, "observation_end": end})
            df = parse_fred_api_json(content)
            _check_nonempty(df, series_id)
            store.save(dataset, "fred_api", f"{FRED_API_URL}?series_id={series_id}", content, "json", len(df),
                       df["date"].min().date(), df["date"].max().date(), units, "observations[].date/value; '.' = missing", rule)
            store.add_status(dataset, "verified_access", "fred_api", f"{len(df)} rows", role)
            return df
        except Exception as exc:
            errors.append(f"fred_api: {exc}")
    # Route 4: local file in FRED format
    local = Path(local_dir) / f"{series_id}.csv"
    if local.exists():
        content = local.read_bytes()
        df = parse_fred_csv(content, series_id)
        store.save(dataset, "local_file", str(local), content, "csv", len(df), df["date"].min().date(),
                   df["date"].max().date(), units, "user-provided FRED-format CSV", rule)
        store.add_status(dataset, "user_provided", "local_file", str(local), role)
        return df
    store.add_status(dataset, "unavailable", "", " | ".join(errors) or "no route succeeded", role)
    raise SourceError(f"{series_id} unavailable. Tried: {' | '.join(errors)}. "
                      f"Fallback: save FRED's CSV as {local}.")


def _parse_cached_fred(store: RawStore, row: dict, series_id: str) -> pd.DataFrame:
    content = store.file_path(row).read_bytes()
    if row["file"].endswith(".json"):
        return parse_fred_api_json(content)
    return parse_fred_csv(content, series_id)


def _check_nonempty(df: pd.DataFrame, name: str) -> None:
    if df.empty or df["value"].notna().sum() == 0:
        raise SourceError(f"{name}: no observations returned")


