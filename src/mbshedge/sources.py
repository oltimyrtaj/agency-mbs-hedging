def load_raw_tables(store: RawStore, cfg: dict) -> dict:
    """Read the latest raw file for every dataset in the manifest into tidy tables."""
    tables = {"fred": {}, "prices": {}, "nmdb": None}
    m = store.manifest()
    if m.empty:
        raise SourceError("The raw manifest is empty. Run notebook 01 first.")
    for dataset in m["dataset"].unique():
        row = m[m["dataset"] == dataset].iloc[-1].to_dict()
        path = store.file_path(row)
        if dataset.startswith("fred_"):
            sid = dataset[len("fred_"):]
            tables["fred"][sid] = _parse_cached_fred(store, row, sid)
        elif dataset.startswith("prices_"):
            tables["prices"][dataset[len("prices_"):]] = parse_price_file(path, row["provider"])
        elif dataset.startswith("fhfa_nmdb"):
            tables["nmdb"] = parse_nmdb(path.read_bytes())
    return tables
